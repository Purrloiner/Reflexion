COMMON_NEWS_INSTRUCTION: Final[str] = """AI-generated fake news can be created in various ways.

1. A completely new news article can be generated based on a headline or other provided information while maintaining a style similar to real news.
2. Some information in an existing real news article can be intentionally modified while preserving the rest of the article. The extent of modification can vary from minor changes to major alterations of the core content, including exaggerating numerical values or changing events and claims.
3. A key sentence that is important to the overall meaning of a real news article can be selected and replaced with inaccurate information that is still plausible and coherent with the surrounding context. Therefore, even if most of the article is factual, one or a few important pieces of information may be false.
4. Propaganda techniques such as loaded language or appeal to authority can be added to inaccurate information to make the content more emotional or persuasive.
5. A real news article may also be gradually distorted as it is transmitted or rewritten. New information or claims may be added, while emotional tone, certainty, wording, temporal information, or perspective may change, causing the article to gradually diverge from the original news.
6. AI can rewrite not only fake news articles but also real news articles while preserving their core factual information and changing only their wording or expression.

You will next be given a news article and must determine whether it was generated by AI.

Use the characteristics and information about AI-generated fake news and modified news described above as prior knowledge when answering the given question."""


