def _is_reflection_classification_feedback(sentence: str) -> bool:
    """Return whether a reflection sentence exposes a prior outcome."""

    candidate = sentence.strip().strip("*_`#> ")
    candidate = re.sub(r"^[-+]\s+", "", candidate)
    return bool(_REFLECTION_BARE_CLASSIFICATION_PATTERN.fullmatch(candidate)) or any(
        pattern.search(candidate)
        for pattern in (
            _REFLECTION_PRIOR_VERDICT_PATTERN,
            _REFLECTION_PRIOR_CLASSIFICATION_PATTERN,
            _REFLECTION_PRIOR_ATTEMPT_OUTCOME_PATTERN,
            _REFLECTION_PRIOR_LABEL_ASSIGNMENT_PATTERN,
            _REFLECTION_PRIOR_DECISION_DIRECTIVE_PATTERN,
            _REFLECTION_CLASSIFICATION_DIRECTIVE_PATTERN,
            _REFLECTION_CLASSIFICATION_SWITCH_PATTERN,
            _REFLECTION_PRONOUN_OUTCOME_PATTERN,
        )
    )


def sanitize_reflection_reasoning(reflection: str) -> str:
    """Return canonical critique reasoning without prior-answer feedback.

    In addition to final-answer syntax handled by :func:`extract_epm_reasoning`,
    Reflection memory must not reveal whether an earlier prediction was right,
    wrong, retained, reversed, or assigned a particular classification.
    """

    if not isinstance(reflection, str):
        return ""
    reasoning_only = extract_epm_reasoning(reflection)
    retained_lines: list[str] = []
    for line in reasoning_only.splitlines():
        stripped = line.strip()
        if not stripped:
            retained_lines.append("")
            continue
        sentences = re.split(r"(?<=[.!?])\s+", stripped)
        retained_lines.append(
            " ".join(
                sentence
                for sentence in sentences
                if sentence and not _is_reflection_classification_feedback(sentence)
            ).strip()
        )

    sanitised = "\n".join(retained_lines).strip()
    sanitised = re.sub(r"\n{3,}", "\n\n", sanitised)
    return extract_epm_reasoning(sanitised)


class PropaNewsDataError(ValueError):
    """Raised when the PropaNews data file does not have the expected shape."""


_OOM_MESSAGE_MARKERS: Final[tuple[str, ...]] = (
    "out of memory",
    "outofmemoryerror",
    "cuda error: out of memory",
    "cuda_error_out_of_memory",
    "cublas_status_alloc_failed",
    "mps backend out of memory",
    "defaultcpuallocator: can't allocate memory",
    "cannot allocate memory",
)


def is_oom_error(error: BaseException) -> bool:
    """Return whether an exception chain represents a local memory exhaustion.

    The check intentionally excludes generic API quota/resource errors.  It
    recognises Python ``MemoryError``, torch-style exception class names, and
    the stable CUDA/MPS/CPU allocator messages used by local model runtimes.
    """

    current: BaseException | None = error
    seen: set[int] = set()
    while current is not None and id(current) not in seen:
        seen.add(id(current))
        if isinstance(current, MemoryError):
            return True
        class_name = type(current).__name__.casefold()
        if class_name in {"outofmemoryerror", "cudaoutofmemoryerror"}:
            return True
        message = str(current).casefold()
        if any(marker in message for marker in _OOM_MESSAGE_MARKERS):
            return True
        current = current.__cause__ or current.__context__
    return False


def recover_from_oom() -> None:
    """Best-effort release of Python and imported torch CUDA/MPS caches."""

    gc.collect()
    torch_module = sys.modules.get("torch")
    if torch_module is None:
        return
    for backend_name in ("cuda", "mps"):
        backend = getattr(torch_module, backend_name, None)
        empty_cache = getattr(backend, "empty_cache", None)
        if callable(empty_cache):
            try:
                empty_cache()
            except Exception:
                # One failing cleanup must neither hide the original OOM nor
                # prevent the other accelerator backend from being released.
                pass


@dataclass(frozen=True, slots=True)
class PromptArticle:
    """The only dataset fields retained by an actor."""

    index: int
    article: str


def _load_rows(path: str | PathLike[str]) -> list[Mapping[str, object]]:
    try:
        with Path(path).open("r", encoding="utf-8") as handle:
            payload = json.load(handle)
    except (OSError, UnicodeError, ValueError) as exc:
        raise PropaNewsDataError(f"cannot load PropaNews data from {path!s}: {exc}") from exc

    if not isinstance(payload, list):
        raise PropaNewsDataError("PropaNews JSON root must be an array")

    rows: list[Mapping[str, object]] = []
    for position, row in enumerate(payload):
        if not isinstance(row, Mapping):
            raise PropaNewsDataError(f"row {position} must be a JSON object")
        rows.append(row)
    return rows


def _validated_index(row: Mapping[str, object], position: int) -> int:
    index = row.get("index")
    if type(index) is not int or index < 0:
        raise PropaNewsDataError(
            f"row {position} index must be a non-negative integer"
        )
    return index


def load_prompt_articles(
    path: str | PathLike[str] = DEFAULT_DATA_PATH,
) -> tuple[PromptArticle, ...]:
    """Return ``index``/``clean_txt`` pairs in exactly the JSON file's order."""

    articles: list[PromptArticle] = []
    seen: set[int] = set()
    for position, row in enumerate(_load_rows(path)):
        index = _validated_index(row, position)
        if index in seen:
            raise PropaNewsDataError(f"duplicate PropaNews index: {index}")
        article = row.get(ARTICLE_TEXT_FIELD)
        if not isinstance(article, str) or not article.strip():
            raise PropaNewsDataError(
                f"row {position} {ARTICLE_TEXT_FIELD} must be a non-empty string"
            )
        seen.add(index)
        articles.append(PromptArticle(index=index, article=article))
    return tuple(articles)


def load_gold_labels(
    path: str | PathLike[str] = DEFAULT_DATA_PATH,
) -> dict[int, bool]:
    """Return evaluation-only boolean labels keyed by the stored index."""

    labels: dict[int, bool] = {}
    for position, row in enumerate(_load_rows(path)):
        index = _validated_index(row, position)
        if index in labels:
            raise PropaNewsDataError(f"duplicate PropaNews index: {index}")
        label = row.get("label")
        if type(label) is not bool:
            raise PropaNewsDataError(f"row {position} label must be a JSON boolean")
        labels[index] = label
    return labels


